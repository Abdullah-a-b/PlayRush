"""Counterfactual rollouts for banking vs risking the next question.

Each paired rollout shares the same random draws. Utility is expected secured
points with a bounded bonus for closing a deficit. The 5-second decision window
and automatic banking at expiry are represented in both branches.
"""
from pathlib import Path
import json
import math
import random

ROOT = Path(__file__).resolve().parents[3]
MODELS=json.loads((ROOT/'Backend/app/domains/games/recall_calibration.json').read_text())
PROFILES={'beginner':(.57,.30,.12,5.5),'medium':(.72,.48,.24,4.6),
          'hard':(.84,.66,.40,3.8),'expert':(.93,.80,.58,3.2)}


def train(level, seed):
    rng=random.Random(seed)
    *priors, think=PROFILES[level]
    bias,slope=MODELS['bank'][level]
    odds=[1/(1+math.exp(-bias-slope*math.log(p/(1-p)))) for p in priors]
    result=[]
    for gap in (-3,0,4):
        for seconds in (7,20,43):
            for tier in range(3):
                row=[]
                for temp in range(1,9):
                    gain=0.
                    for _ in range(700):
                        delay=think+rng.uniform(0,3)
                        knows=rng.random()
                        horizon=seconds+rng.uniform(-3,3)
                        # Following the next attempt both branches secure their balance.
                        bank=temp+int(horizon>1.6+delay and knows<odds[0])
                        risk=temp if horizon<=5+delay else (temp+tier+1 if knows<odds[tier] else 0)
                        def utility(points):
                            return points+(2 if gap>0 and points>gap else 0)
                        gain+=utility(bank)-utility(risk)
                    row.append(round(.12+.76/(1+math.exp(-2*gain/700)),3))
                result.append(row)
    return result


if __name__=='__main__':
    table={level:train(level,93871+i) for i,level in enumerate(PROFILES)}
    (ROOT/'FrontEnd/js/bank_risk_model.js').write_text(
        '// Generated by train_bank_risk.py\nconst BANK_RISK = '+json.dumps(table)+';\n',encoding='utf8')
