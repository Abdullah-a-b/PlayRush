"""Fit compact recall curves to synthetic contestants, and test on fresh contestants.

Input is the existing game's estimate using only information available at decision
time. A synthetic contestant has a stable familiarity bias and occasionally fails
to retrieve a familiar answer. These are design assumptions, not player telemetry.
"""
import json
import math
from pathlib import Path
import random

ROOT = Path(__file__).resolve().parents[3]
LEVELS = ('beginner', 'medium', 'hard', 'expert')
# Odds offsets for easy through expert; variance reflects uncertainty in each game.
SCENARIOS = {
    'huroof': ((-.35, -.16, -.04, .01), .40),
    'career': ((-.30, -.14, -.02, .05), .55),
    'whoami': ((-.36, -.16, .01, .12), .48),
    'knowledge': ((-.28, -.12, .00, .08), .42),
    'bank': ((-.36, -.14, .00, .10), .50),
}


def sigmoid(x):
    return 1 / (1 + math.exp(-x))


def examples(rng, count, bias, variation, level):
    for _ in range(count // 8):
        familiarity = rng.gauss(bias, variation)
        for _ in range(8):
            prior = rng.uniform(.002, .998)
            log_odds = math.log(prior / (1-prior))
            # Hard-to-recall items penalize novices more; even experts can blank.
            recall = sigmoid((1.18 - .045*level)*log_odds + familiarity)
            yield log_odds, int(rng.random() < recall*(.96+.006*level))


def fit(game, level, index, seed):
    offsets, variation = SCENARIOS[game]
    args = offsets[index], variation, index
    intercept, slope = 0., 1.
    for step, (x, y) in enumerate(examples(random.Random(seed), 120000, *args)):
        error = y - sigmoid(intercept + slope*x)
        rate = .035 / (1+step/5000)
        intercept += rate*error
        slope += rate*error*x
    validation = list(examples(random.Random(seed+50000), 24000, *args))
    def loss(a,b):
        return sum((sigmoid(a+b*x)-y)**2 for x,y in validation)/len(validation)
    old, new = loss(0,1), loss(intercept,slope)
    # Keep the prior if the fit doesn't generalize on the validation seed.
    if new >= old:
        intercept,slope=0.,1.
    print(game, level, 'validation Brier', round(old,5), '->',round(min(old,new),5))
    return [round(intercept,6),round(slope,6)]


if __name__ == '__main__':
    result = {g:{l:fit(g,l,i,20261122+1000*j+i) for i,l in enumerate(LEVELS)}
              for j,g in enumerate(SCENARIOS)}
    content=json.dumps(result,indent=2)+'\n'
    (ROOT/'Backend/app/domains/games/recall_calibration.json').write_text(content,encoding='utf8')
    (ROOT/'FrontEnd/js/solo_recall.js').write_text(
        '// Generated by train_solo_recall.py\nconst PR_RECALL = '+content.rstrip()+';\n'+
        """function practiceRecall(game, level, prior) {
    if (prior <= 0 || prior >= 1) return prior;
    const [bias, slope] = PR_RECALL[game][level] || PR_RECALL[game].medium;
    return 1 / (1 + Math.exp(-bias - slope * Math.log(prior / (1 - prior))));
}
""",encoding='utf8')
